import { normalizePath } from "@typespec/compiler";
import type { DocumentTarget } from "./resolve.js";

/** The header every emitted file carries. */
const GENERATED_BANNER = `// GENERATED by typespec-openapi-document from the TypeSpec service definition. DO NOT EDIT.
// Recompile the spec that produced it; edits here are overwritten on the next run.
`;

/**
 * A path from the generated module to the document, spelled the way a module resolver reads it.
 *
 * **Relative, never absolute.** An absolute path bakes one machine's checkout into generated
 * output that the consumer then commits. It resolves perfectly for whoever ran the emitter and for
 * nobody else. The sibling packages both guard this as a class for exactly that reason.
 *
 * **And explicitly prefixed `./` when it does not already start with `..`.** A bare `openapi.json`
 * is a PACKAGE specifier to every module resolver, not a sibling file, so the import would resolve to
 * a dependency that does not exist rather than to the document one directory away.
 *
 * **Both paths are normalised first.** An output directory may be configured through `..`, as a
 * monorepo's spec package names its neighbours, and compared segment by segment a literal `..` is a
 * directory: where the two paths climbed a different number of levels, the import pointed outside
 * the project.
 */
function relativeSpecifier(from: string, to: string): string {
	const fromParts = normalizePath(from)
		.split("/")
		.filter((part) => part !== "");
	const toParts = normalizePath(to)
		.split("/")
		.filter((part) => part !== "");
	let shared = 0;
	while (
		shared < fromParts.length &&
		shared < toParts.length &&
		fromParts[shared] === toParts[shared]
	) {
		shared++;
	}
	const up = Array.from({ length: fromParts.length - shared }, () => "..");
	const down = toParts.slice(shared);
	const joined = [...up, ...down].join("/");
	return joined.startsWith(".") ? joined : `./${joined}`;
}

/**
 * The generated module: the document, and the path it is conventionally served at.
 *
 * **An import, not a file read.** The document becomes part of the consumer's bundle, which is what
 * makes it impossible to serve a stale one: it cannot drift from the build, and a missing one is a
 * build failure rather than a 500 at runtime. JSON compresses well, so even a document describing
 * hundreds of operations is noise against a Worker's 3 MB budget.
 *
 * **`with { type: "json" }` is required, and it is why YAML is refused upstream of here.** The
 * import attribute is what makes this legal in a standards-compliant module resolver rather than a
 * bundler-specific convenience.
 *
 * **No route, no server, no framework.** The consumer mounts it in two lines with whatever they
 * already have. That is the whole point of this being its own package rather than part of a server
 * generator.
 */
/** One document, and the version it belongs to when the service declares any. */
export interface VersionedTarget extends DocumentTarget {
	readonly version: string | undefined;
}

export function renderModule(targets: readonly VersionedTarget[], moduleDir: string): string {
	const versioned = targets.length > 1 || targets[0]?.version !== undefined;
	const imports = targets.map((target, index) => {
		const specifier = relativeSpecifier(moduleDir, target.path);
		return `import document${index} from ${JSON.stringify(specifier)} with { type: "json" };`;
	});

	/**
	 * **The LAST declared version is the current one, and that is not the same as the last by
	 * name.** `v1, v2preview, v2` sorts as `v1, v2, v2preview`, so picking by filename hands a consumer
	 * a PREVIEW as though it were current. The sibling library's differential did exactly that and it
	 * hid a real defect. `versionsOf` returns declaration order and this takes its last entry.
	 */
	const currentIndex = targets.length - 1;
	const byVersion = targets
		.map((target, index) => `\t${JSON.stringify(target.version ?? "")}: document${index},`)
		.join("\n");

	const versionBlock = versioned
		? `
/**
 * Every version this service declares, keyed by version name.
 *
 * **\`openApiDocument\` is the LAST DECLARED version, not the last alphabetically.** A version name
 * sorts however its author spelled it (\`v1, v2preview, v2\` sorts as \`v1, v2, v2preview\`) so only
 * the declaration order says which one is current.
 */
export const openApiDocumentsByVersion = {
${byVersion}
} as const;

/** The versions this service declares, oldest first. */
export const OPENAPI_VERSIONS = ${JSON.stringify(targets.map((t) => t.version ?? ""))} as const;
`
		: "";

	return `${GENERATED_BANNER}
/**
 * The OpenAPI document \`@typespec/openapi3\` produced from this spec, as a value.
 *
 * Imported rather than read from disk, so it is part of your bundle: it cannot go stale relative to
 * the build, and a missing document fails the build rather than a request.
 */
${imports.join("\n")}

/** The document for the version this service currently serves. */
export const openApiDocument = document${currentIndex};
${versionBlock}
/** The path this document is conventionally served at. Yours to change; nothing here depends on it. */
export const OPENAPI_DOCUMENT_PATH = "/openapi.json";
`;
}
